/* ------------------------------- helpers -------------------------------- */

function L(fa, en) {
  return { fa: String(fa), en: String(en) };
}

function isNonEmptyString(v) {
  return typeof v === "string" && v.trim().length > 0;
}

function isLocalized(v) {
  return (
    !!v &&
    typeof v === "object" &&
    isNonEmptyString(v.fa) &&
    isNonEmptyString(v.en)
  );
}

function fail(errors, msg) {
  errors.push(msg);
}

